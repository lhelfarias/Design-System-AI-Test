// Generates css/tokens.css (CSS custom properties) from tokens.json with Style Dictionary.
//   - One variable per token, same path as in Figma: color/text/default -> --color-text-default
//   - Aliases are kept as var(--...) so the reference -> system -> component layers survive in CSS
//   - Typography tokens become a `font` shorthand: font: var(--typography-body)
import StyleDictionary from "style-dictionary";
import { join } from "node:path";
import { ROOT, SETS, loadSets, flatten } from "./lib.mjs";

const sets = loadSets();
flatten(sets); // throws on duplicate token paths across sets

// Tokens Studio keeps one set per top-level key; Style Dictionary needs one tree.
// Each token remembers its set so the CSS file can be grouped by layer.
const tag = (node, set) => {
  if (Object.prototype.hasOwnProperty.call(node, "$value")) return { ...node, set };
  return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, k.startsWith("$") ? v : tag(v, set)]));
};
const merge = (a, b) => {
  for (const [k, v] of Object.entries(b)) {
    if (a[k] && typeof a[k] === "object" && !("$value" in a[k]) && typeof v === "object" && !("$value" in v)) merge(a[k], v);
    else a[k] = v;
  }
  return a;
};
const tokens = SETS.reduce((acc, name) => merge(acc, tag(sets[name], name)), {});

const quoteFamily = (v) =>
  String(v).split(",").map((f) => f.trim()).map((f) => (/\s/.test(f) && !/^["']/.test(f) ? `"${f}"` : f)).join(", ");
const unitless = (v) => {
  const m = String(v).match(/^(\d+(?:\.\d+)?)%$/);
  return m ? String(Number(m[1]) / 100) : String(v);
};

// Tokens Studio stores line height as a percentage so Figma reads a multiplier; CSS wants a unitless number.
StyleDictionary.registerTransform({
  name: "ds/line-height",
  type: "value",
  filter: (t) => t.$type === "lineHeights",
  transform: (t) => unitless(t.$value),
});
StyleDictionary.registerTransform({
  name: "ds/font-family",
  type: "value",
  filter: (t) => t.$type === "fontFamily",
  transform: (t) => quoteFamily(t.$value),
});
// CSS font shorthand: <weight> <size>/<line-height> <family>. Letter spacing is 0 in every style, so it is not emitted.
StyleDictionary.registerTransform({
  name: "ds/typography-shorthand",
  type: "value",
  transitive: true,
  filter: (t) => t.$type === "typography" && typeof t.$value === "object",
  transform: (t) => {
    const v = t.$value;
    return `${v.fontWeight} ${v.fontSize}/${unitless(v.lineHeight)} ${quoteFamily(v.fontFamily)}`;
  },
});

const LAYER_NOTE = {
  reference: "Raw values. Do not use in components.",
  system: "Meaning. Use these in pages and components.",
  component: "Component decisions. Use inside the named component only.",
};
StyleDictionary.registerFormat({
  name: "ds/css-by-layer",
  format: ({ dictionary, options }) => {
    const refs = options.outputReferences;
    const byPath = new Map(dictionary.allTokens.map((t) => [t.path.join("."), t]));
    const line = (t) => {
      const original = t.original.$value;
      const alias = typeof original === "string" && original.match(/^\{([^{}]+)\}$/);
      const value = refs && alias && byPath.has(alias[1]) ? `var(--${byPath.get(alias[1]).name})` : t.$value;
      return `  --${t.name}: ${value};`;
    };
    const blocks = SETS.map((set) => {
      const list = dictionary.allTokens.filter((t) => t.set === set);
      return `  /* ${set} (${list.length}). ${LAYER_NOTE[set]} */\n${list.map(line).join("\n")}`;
    });
    return `/* Generated by scripts/build-css.mjs from tokens.json. Do not edit. */\n:root {\n${blocks.join("\n\n")}\n}\n`;
  },
});

const sd = new StyleDictionary({
  tokens,
  usesDtcg: true,
  log: { verbosity: "verbose" },
  platforms: {
    css: {
      transforms: ["name/kebab", "ds/line-height", "ds/font-family", "ds/typography-shorthand"],
      buildPath: join(ROOT, "css") + "/",
      files: [{ destination: "tokens.css", format: "ds/css-by-layer", options: { outputReferences: true } }],
    },
  },
});
await sd.buildAllPlatforms();

// Safety check: every var(--x) used in the file must be defined in it.
import { readFileSync } from "node:fs";
const css = readFileSync(join(ROOT, "css", "tokens.css"), "utf8");
const defined = new Set([...css.matchAll(/^\s*(--[\w-]+):/gm)].map((m) => m[1]));
const missing = [...new Set([...css.matchAll(/var\((--[\w-]+)\)/g)].map((m) => m[1]))].filter((v) => !defined.has(v));
if (missing.length) throw new Error(`Undefined CSS variables: ${missing.join(", ")}`);
console.log(`OK: ${defined.size} CSS variables, all references defined`);
